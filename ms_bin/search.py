"""Ключ поиска для названий ячеек.

Названия заводят вручную: латиница вперемешку с кириллицей, разные пробелы и дефисы.
Одна функция и для базы, и для запроса — иначе поиск не найдёт.
Ключ машинный, для показа пользователю не предназначен.
"""
import re

# Латинские двойники кириллических букв (в нижнем регистре, после casefold)
_LATIN_TO_CYRILLIC = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к",
    "m": "м", "o": "о", "p": "р", "t": "т", "x": "х", "y": "у",
})
_SEPARATORS = re.compile(r"[\s\-_.,/]+")


def search_key(text: str) -> str:
    key = text.casefold().replace("ё", "е")
    key = key.translate(_LATIN_TO_CYRILLIC)
    return _SEPARATORS.sub("", key)